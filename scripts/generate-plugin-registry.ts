import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

/** Shared by full tool generation and the registry-only refresh. */
export function generatePluginRegistrySource(aliases: string[]): string {
  const registrations = aliases
    .map((alias) => {
      const exportName =
        alias
          .split(/[-_]/)
          .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
          .join('') + 'Plugin';

      return `  await loadPlugin({ alias: ${JSON.stringify(alias)}, load: async () => (await import(${JSON.stringify(`../plugins/${alias}/init`)})).${exportName}, ctx });`;
    })
    .join('\n');

  return `// generated/plugins.ts — AUTO-GENERATED, do not edit
// Generated by: bun run plugin:generate or bun scripts/generate-plugin-registry.ts

import type { PluginHostContext } from '../src/core/plugin';
import { loadPlugin } from '../src/core/plugin-loading';

export async function registerPlugins(ctx: PluginHostContext): Promise<void> {
${registrations}
}
`;
}

if (import.meta.main) {
  const root = join(import.meta.dir, '..');

  const installed = JSON.parse(
    readFileSync(join(root, 'plugins.json'), 'utf8'),
  ) as { plugins: { alias: string }[] };

  writeFileSync(
    join(root, 'generated', 'plugins.ts'),
    generatePluginRegistrySource(installed.plugins.map((entry) => entry.alias)),
    'utf8',
  );

  console.log('[generate-plugin-registry] Generated generated/plugins.ts');
}
